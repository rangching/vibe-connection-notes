"""EP9 練習題答案：分而合之。
群體占比 s = n_g / N；多樣性指數（Blau 指數）D = 1 - Σ p_k^2：
隨機抽兩人，來自不同背景的機率。分類帽（依相似性分院）每院 D=0；橫切面（依多樣性平衡）每院 D=全校值。"""
N, houses = 900, 4
