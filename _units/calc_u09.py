# 假設：全校四種背景比例 40%、30%、20%、10%
p = [0.40, 0.30, 0.20, 0.10]
D = 1 - sum(x * x for x in p)
print("Q4 全校 Blau 多樣性指數 D            =", round(D, 2))
print("   分類帽（同質院）每院 D            =", 0.0)
print("   橫切面（縮影院）每院 D            =", round(D, 2))
