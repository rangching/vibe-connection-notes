"""EP8 練習題答案：設計一場聚會。
n 個人之間的兩兩關係數 C(n,2)=n(n-1)/2；三人組數 C(n,3)；比值與倍數。"""
from math import comb
for n in (2, 3, 4, 8, 10, 14):
    print(f"   n={n:>2}  兩兩關係 {comb(n,2):>3}  三人組 {comb(n,3):>3}")
print("Q1 Jefferson 晚宴 14 人的兩兩關係數 =", comb(14, 2))
print("Q2 從 8 人到 14 人，關係數變成幾倍  =", round(comb(14, 2) / comb(8, 2), 2))
print("Q3 雙人房 45% ÷ 三人房 29%          =", round(45 / 29, 2))
# 假設：一位女性對照組參加者在研討會認識 7 位新朋友；書中說收到名單的女性多認識 57%
print("Q4 假設對照組認識 7 人，×1.57       =", round(7 * 1.57, 2))
# 書中：每千名員工每年因多餘會議浪費 2,500 萬美元
print("Q5 250 人公司每年浪費 (萬美元)       =", 2500 * 250 / 1000)
# 書中：刪除所有例行會議後平均每月省 11 小時
print("Q6 每月省 11 小時，一年省 (小時)     =", 11 * 12)
