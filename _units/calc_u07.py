"""EP7 練習題答案：好好吵架。用機率比較看衝突處理的效果。
相對變化 (p1-p0)/p0；風險比 RR = p1/p0；勝算比 OR = [p1/(1-p1)] / [p0/(1-p0)]。
書中數字：調解者對雙方表達敵意，僵局後達成協議率 59% → 85%；
同儕調解 4,000 件以上，解決率 93%、滿意度 88%；新婚看電影實驗 3 年後分居或離婚機率約為對照組一半。"""
p0, p1 = 0.59, 0.85
print("Q1 59%→85% 增加的百分點          =", round((p1 - p0) * 100, 1))
print("Q2 59%→85% 相對增幅 (%)          =", round((p1 - p0) / p0 * 100, 1))
odds = lambda p: p / (1 - p)
print("Q3 勝算比 OR                      =", round(odds(p1) / odds(p0), 2), " (勝算", round(odds(p0), 3), "→", round(odds(p1), 3), ")")
n = 4000
print("Q4 4000 件 × 93% 解決 (件)        =", round(n * 0.93))
print("   4000 件中未解決 (件)            =", round(n * 0.07))
# 假設情境：對照組 3 年內分居或離婚率 20%，每組 300 對；實驗組約為一半
base, couples = 0.20, 300
treat = base / 2
print("Q5 假設對照 20%，實驗組 (%)        =", round(treat * 100, 1))
print("   每 300 對少幾對分居或離婚        =", round(couples * (base - treat)))
# 假設情境：兩人各自爬三層推論階梯，每層各有 3 種可能詮釋
print("Q6 一人三層、每層 3 種詮釋的路徑數 =", 3 ** 3)
print("   兩人路徑組合數                  =", (3 ** 3) ** 2, "；兩人恰好走到同一條路徑的機率 =", round(1 / 27, 4))
