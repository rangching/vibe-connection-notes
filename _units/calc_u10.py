"""EP10 團隊同步：練習題答案。
資料來源：《Vibe》〈All for One〉與尾註。虛構情境（基準值）在題目中標明為假設。
核心式：回饋階梯的「仍未改過比例」1-p 與再犯比 (1-p_類別)/(1-p_即時)。"""
from math import comb

# League of Legends 改革卡三個版本的改過率（書中數字）
p = {"只列類別": 0.50, "附具體聊天紀錄": 0.70, "5–10 分鐘內具體回饋": 0.92}
for k, v in p.items():
    print(f"未改過比例 1-p  {k:<14} = {1 - v:.2f}")
q1 = (1 - p["只列類別"]) / (1 - p["5–10 分鐘內具體回饋"])
print("Q1 再犯比 0.50/0.08                 =", round(q1, 2))
q2 = ((1 - p["附具體聊天紀錄"]) - (1 - p["5–10 分鐘內具體回饋"])) / (1 - p["附具體聊天紀錄"])
print("Q2 加上即時後，未改過者相對降幅(%)  =", round(100 * q2, 1))

# 開放式辦公室：面對面協作下降 70%（假設原本每週 40 次）
print("Q3 40 次 × (1-0.70)                  =", round(40 * (1 - 0.70), 1))

# 價值觀排名：兩兩比較次數 k(k-1)/2
for k in (4, 10, 25):
    print(f"   兩兩比較 C({k},2)                 =", comb(k, 2))
print("Q4 10 條 vs 4 條的比較次數倍數       =", round(comb(10, 2) / comb(4, 2), 2))

# 2024 巴黎奧運 18 名奪金球員中只有 8 名參加過東京奧運
print("Q5 8/18 (%)                          =", round(100 * 8 / 18, 1))

# 醫院：被羞辱後正確率約低 15%（相對）；假設基準正確率 80%
print("Q6 80% × (1-0.15) (%)                =", round(80 * (1 - 0.15), 1))

# 統合分析：195 項研究、12,000 多支團隊 → 平均每項研究至少幾支
print("   12000/195                         =", round(12000 / 195, 1))
